export type TranslationKey = keyof typeof zh;

export function resolveLanguage(language: AppLanguage): "zh-CN" | "en-US" {
  if (language !== "system") return language;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}

export function translator(language: AppLanguage) {
  const messages = resolveLanguage(language) === "zh-CN" ? zh : en;
  return (key: TranslationKey) => messages[key];
}
